#!/usr/bin/env python3
"""Generate the daily ARCSTUDIO91 carousel visuals with a free local open-weight model.

This script deliberately uses a local FLUX.1-schnell model. It does not call a hosted
inference API, paid image service, or paid generation-credit system. A compatible local
NVIDIA GPU is required; if unavailable, the script fails rather than silently changing
to stock photos or pretending non-AI artwork was generated by AI.
"""
from __future__ import annotations

import hashlib
import importlib.metadata
import io
import json
import os
from datetime import date
from pathlib import Path
import sys
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(os.environ.get("ARCSTUDIO_OUTPUT_DIR", str(ROOT / "output" / "current"))).resolve()
OUT.mkdir(parents=True, exist_ok=True)
sys.path.insert(0, str(ROOT / "scripts"))

import torch
from diffusers import FluxPipeline
from PIL import Image, ImageOps

import generate_daily as gd

MODEL_ID = "black-forest-labs/FLUX.1-schnell"
MODEL_LICENSE = "Apache-2.0"
IMAGE_SIZE = (1024, 1280)  # width, height: 4:5-ish portrait; final crop is 1080×1350
STEPS = 4
GUIDANCE = 0.0

def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()

def build_prompts(concept: dict[str, Any]) -> list[dict[str, str]]:
    typology = concept.get("type", "architecture")
    idea = concept.get("original_idea", "a practical, climate-aware architecture concept")
    climate = concept.get("comfort", "daylight, shade and clear circulation")
    care = concept.get("life", "repairability, safe inspection and easy maintenance")
    materials = concept.get("materials", ["natural, locally available materials"])
    material_text = ", ".join(str(x) for x in materials[:3]) if isinstance(materials, list) else str(materials)
    shared = (
        f"Architecture editorial photography for an original {typology} design study. "
        f"Design brief: {idea}. Contemporary, restrained, climate-aware design, realistic buildable proportions, "
        "high-quality architectural photography, accurate perspective, tactile natural materials, realistic daylight, "
        "professional camera framing, sophisticated but quiet composition, warm neutral palette, deep green accents, "
        "minimal functional design, subtle imperfections that feel real, no people, no logos, no text, no watermark, "
        "no labels, no collage, no split screen, no fake signage, no fantasy structure, no excessive luxury styling."
    )
    return [
        {
            "role": "cover",
            "prompt": shared + " Hero exterior or threshold view, beautiful but plausible architecture, readable main silhouette, layered shade, planted edge, natural side light, portrait 4:5 framing, leave a calm darker zone near the lower third for overlay text.",
        },
        {
            "role": "climate",
            "prompt": shared + f" A single coherent view that communicates this practical climate/space insight: {climate}. Show believable window placement, daylight and shade interacting naturally. No diagram labels or visible text.",
        },
        {
            "role": "maintenance",
            "prompt": shared + f" A close architectural detail illustrating careful long-term design: {care}. Show real material junctions, accessible exterior details, honest construction texture, safe and plausible maintenance access, crisp but not over-sharpened.",
        },
        {
            "role": "materials",
            "prompt": shared + f" A restrained material-led architectural scene using this material direction: {material_text}. Natural stone, timber, masonry or mineral finishes only where suitable; real texture, soft daylight, practical surfaces, coherent composition with negative space for overlaid copy.",
        },
    ]

def load_pipeline():
    if not torch.cuda.is_available():
        raise RuntimeError(
            "Strict free-AI mode requires a compatible local CUDA GPU. No GPU detected. "
            "No paid API, paid credit, image-generation service or stock-photo fallback will be used. "
            "Install a CUDA-enabled PyTorch build and ensure the GPU has enough memory, then retry."
        )
    # FLUX.1-schnell is a 12B-parameter model. Model weights are downloaded once and
    # cached locally. CPU offload reduces VRAM pressure at the cost of slower rendering.
    dtype = torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16
    pipe = FluxPipeline.from_pretrained(
        MODEL_ID,
        torch_dtype=dtype,
        use_safetensors=True,
    )
    pipe.enable_model_cpu_offload()
    pipe.set_progress_bar_config(disable=False)
    return pipe

def run() -> None:
    concept_path = OUT / "concept.json"
    if not concept_path.is_file():
        raise RuntimeError(f"Missing {concept_path}; download the cloud source pack first.")
    concept = json.loads(concept_path.read_text(encoding="utf-8"))
    current_date = concept.get("date", date.today().isoformat())
    prompts = build_prompts(concept)
    pipe = load_pipeline()

    generated: list[dict[str, Any]] = []
    prompt_manifest: list[dict[str, Any]] = []
    try:
        for index, item in enumerate(prompts, start=1):
            seed = int(hashlib.sha256(f"{current_date}:{concept.get('type')}:{item['role']}".encode()).hexdigest()[:8], 16)
            generator = torch.Generator(device="cuda").manual_seed(seed)
            result = pipe(
                prompt=item["prompt"],
                width=IMAGE_SIZE[0],
                height=IMAGE_SIZE[1],
                num_inference_steps=STEPS,
                guidance_scale=GUIDANCE,
                generator=generator,
                max_sequence_length=256,
            )
            image = result.images[0].convert("RGB")
            bg_path = OUT / f"ai_background_{index:02d}.png"
            image.save(bg_path, format="PNG", optimize=True)

            buffer = io.BytesIO()
            image.save(buffer, format="JPEG", quality=95, optimize=True, subsampling=0)
            generated.append({
                "title": f"ARCSTUDIO91 AI concept visual — {item['role']}",
                "bytes": buffer.getvalue(),
                "license": f"Output generated locally with {MODEL_ID}; model licence {MODEL_LICENSE}",
                "license_url": "https://huggingface.co/black-forest-labs/FLUX.1-schnell",
                "artist": f"Generated locally by ARCSTUDIO91 workflow using {MODEL_ID}",
                "source_page": "AI-generated concept artwork; not a real project photograph",
                "ai_generated": True,
                "model_id": MODEL_ID,
                "prompt": item["prompt"],
                "seed": seed,
                "role": item["role"],
                "file": bg_path.name,
                "sha256": sha256_file(bg_path),
            })
            prompt_manifest.append({
                "index": index,
                "role": item["role"],
                "prompt": item["prompt"],
                "seed": seed,
                "file": bg_path.name,
                "sha256": sha256_file(bg_path),
            })

            # Same-day AI backgrounds feed the Reel as well; no external imagery is used.
            reel_source = ImageOps.fit(image, gd.SIZE, method=Image.Resampling.LANCZOS, centering=(0.5, 0.45))
            reel_source.save(OUT / f"_reel_source_{index:02d}.jpg", quality=95, optimize=True)

            # Generate each carousel slide separately. Pillow adds exact, editable typography.
            gd.render_slide(generated[-1], concept, index)

    finally:
        del pipe
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    contact_sheet = gd.create_contact_sheet([OUT / f"slide_{i:02d}.jpg" for i in range(1, 5)])
    caption = gd.make_caption(concept, generated, date.fromisoformat(current_date))
    research = gd.write_research_notes(concept, generated, date.fromisoformat(current_date))

    source_metadata = {
        "date": current_date,
        "pillar": gd.editorial_pillar(concept),
        "concept": concept.get("type"),
        "headline": concept.get("headline"),
        "visual_mode": "locally generated open-weight AI concept visuals",
        "ai_model": MODEL_ID,
        "ai_model_license": MODEL_LICENSE,
        "photos": [{k: v for k, v in p.items() if k != "bytes"} for p in generated],
        "files": [f"slide_{i:02d}.jpg" for i in range(1, 5)],
        "contact_sheet": contact_sheet.name,
        "caption_length": len(caption),
    }
    (OUT / "sources.json").write_text(json.dumps(source_metadata, ensure_ascii=False, indent=2), encoding="utf-8")
    concept["visual_mode"] = "locally generated open-weight AI concept artwork"
    concept["ai_model"] = MODEL_ID
    concept["ai_model_license"] = MODEL_LICENSE
    (OUT / "concept.json").write_text(json.dumps(concept, ensure_ascii=False, indent=2), encoding="utf-8")

    manifest = {
        "date": current_date,
        "mode": "local open-weight inference; no paid hosted API",
        "model_id": MODEL_ID,
        "model_license": MODEL_LICENSE,
        "model_card": "https://huggingface.co/black-forest-labs/FLUX.1-schnell",
        "pipeline": "Diffusers FluxPipeline",
        "inference_steps": STEPS,
        "guidance_scale": GUIDANCE,
        "dimensions_before_overlay": {"width": IMAGE_SIZE[0], "height": IMAGE_SIZE[1]},
        "prompts": prompt_manifest,
        "notes": "AI-generated conceptual visuals, not representations of completed or commissioned projects.",
    }
    (OUT / "ai_generation_manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    (OUT / "research_notes.md").write_text(
        research.read_text(encoding="utf-8")
        + "\n\n## Strict free-AI provenance\n"
        + f"- Model: {MODEL_ID}\n- Model licence: {MODEL_LICENSE}\n"
        + "- Ran locally with open weights. No paid inference endpoint, paid API, paid generation credits, or licensed stock photo was used for the visual images.\n"
        + "- Prompt/seed/model settings: ai_generation_manifest.json\n",
        encoding="utf-8",
    )

    print(f"Generated 4 AI image backgrounds and 4 separate carousel slides for {current_date}.")
    print(f"Visual model: {MODEL_ID} ({MODEL_LICENSE}); prompts and seeds saved to ai_generation_manifest.json.")

if __name__ == "__main__":
    run()
